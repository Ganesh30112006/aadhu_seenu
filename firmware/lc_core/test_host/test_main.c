#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

static int failures = 0;
static int checks = 0;

#define CHECK(cond)                                                          \
    do {                                                                     \
        checks++;                                                            \
        if (!(cond)) {                                                       \
            failures++;                                                      \
            fprintf(stderr, "FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond); \
        }                                                                    \
    } while (0)

/* ── frame ─────────────────────────────────────────────────────────────── */
static void test_frame(void) {
    uint8_t buf[LC_FRAME_HEADER_LEN + 8];
    lc_frame_header_t h = {LC_CODEC_PCM16, 0x01020304u, 0x1122334455667788ull, 1700000000123ull, 8};
    CHECK(lc_frame_encode_header(&h, buf) == LC_FRAME_HEADER_LEN);
    CHECK(buf[0] == 'L' && buf[1] == 'C' && buf[2] == 1 && buf[3] == 0);
    CHECK(buf[4] == 0x04 && buf[7] == 0x01);   /* little-endian seq */
    CHECK(buf[8] == 0x88 && buf[15] == 0x11);  /* little-endian sample_offset */
    CHECK(buf[24] == 8 && buf[25] == 0);
    memset(buf + LC_FRAME_HEADER_LEN, 0, 8);
    lc_frame_header_t out;
    CHECK(lc_frame_decode(buf, sizeof buf, &out) == LC_FRAME_OK);
    CHECK(out.seq == h.seq && out.sample_offset == h.sample_offset && out.capture_unix_ms == h.capture_unix_ms);
    CHECK(lc_frame_decode(buf, sizeof buf - 1, &out) == LC_FRAME_ERR_LENGTH);
    CHECK(lc_frame_decode(buf, 10, &out) == LC_FRAME_ERR_SHORT);
    buf[0] = 'X';
    CHECK(lc_frame_decode(buf, sizeof buf, &out) == LC_FRAME_ERR_MAGIC);
    buf[0] = 'L';
    buf[3] = 7;
    CHECK(lc_frame_decode(buf, sizeof buf, &out) == LC_FRAME_ERR_CODEC);
}

/* ── adpcm ─────────────────────────────────────────────────────────────── */
static double snr_db(const int16_t *a, const int16_t *b, size_t n) {
    double signal = 0, noise = 0;
    for (size_t i = 0; i < n; i++) {
        signal += (double)a[i] * a[i];
        noise += (double)(a[i] - b[i]) * (a[i] - b[i]);
    }
    return noise == 0 ? 120.0 : 10.0 * log10(signal / noise);
}

static size_t read_file(const char *path, uint8_t *dst, size_t cap) {
    FILE *f = fopen(path, "rb");
    if (f == NULL) return 0;
    size_t n = fread(dst, 1, cap, f);
    fclose(f);
    return n;
}

static void test_adpcm(void) {
    static int16_t pcm[LC_SAMPLES_PER_CHUNK];
    static int16_t decoded[LC_SAMPLES_PER_CHUNK + 4];
    static uint8_t enc[LC_ADPCM_CHUNK_BYTES];
    for (size_t i = 0; i < LC_SAMPLES_PER_CHUNK; i++) {
        pcm[i] = (int16_t)(8000.0 * sin(2 * M_PI * 440.0 * (double)i / 16000.0) +
                           3000.0 * sin(2 * M_PI * 1250.0 * (double)i / 16000.0));
    }
    CHECK(lc_adpcm_encoded_size(LC_SAMPLES_PER_CHUNK) == LC_ADPCM_CHUNK_BYTES);
    CHECK(lc_adpcm_encode(pcm, LC_SAMPLES_PER_CHUNK, enc) == LC_ADPCM_CHUNK_BYTES);
    CHECK(enc[3] == 1); /* 7999 codes: last nibble is padding */
    size_t n = lc_adpcm_decode(enc, LC_ADPCM_CHUNK_BYTES, decoded, LC_SAMPLES_PER_CHUNK + 4);
    CHECK(n == LC_SAMPLES_PER_CHUNK);
    CHECK(decoded[0] == pcm[0]);
    CHECK(snr_db(pcm, decoded, LC_SAMPLES_PER_CHUNK) > 15.0); /* conservative bound for 4-bit IMA */

    /* Odd-length final chunk decodes to exactly its sample count. */
    CHECK(lc_adpcm_encode(pcm, 7, enc) == 4 + 3);
    CHECK(lc_adpcm_decode(enc, 7, decoded, 100) == 7);
    CHECK(lc_adpcm_encode(pcm, 8, enc) == 4 + 4);
    CHECK(lc_adpcm_decode(enc, 8, decoded, 100) == 8);
    uint8_t bad[4] = {0, 0, 0, 1};
    CHECK(lc_adpcm_decode(bad, 4, decoded, 10) == 0);

    /* Cross-language vectors generated by backend/app/audio/adpcm.py. */
    static uint8_t raw[LC_PCM_CHUNK_BYTES];
    static uint8_t expected[LC_ADPCM_CHUNK_BYTES];
    size_t pcm_bytes = read_file("contracts/test_vectors/adpcm_input.pcm", raw, sizeof raw);
    size_t exp_bytes = read_file("contracts/test_vectors/adpcm_expected.bin", expected, sizeof expected);
    if (pcm_bytes == 0 || exp_bytes == 0) {
        fprintf(stderr, "note: contracts/test_vectors not found (run from repo root); cross-check skipped\n");
        return;
    }
    size_t samples = pcm_bytes / 2;
    for (size_t i = 0; i < samples; i++) pcm[i] = (int16_t)(raw[2 * i] | (raw[2 * i + 1] << 8));
    size_t written = lc_adpcm_encode(pcm, samples, enc);
    CHECK(written == exp_bytes);
    CHECK(memcmp(enc, expected, exp_bytes) == 0);
}

/* ── ack + ring ────────────────────────────────────────────────────────── */
static void test_ack_and_ring(void) {
    lc_ack_t ack;
    lc_ack_reset(&ack);
    CHECK(!lc_ack_covers(&ack, 0));
    ack.cumulative = 4;
    CHECK(lc_ack_covers(&ack, 4) && !lc_ack_covers(&ack, 5));
    CHECK(lc_ack_add_range(&ack, 9, 11));
    CHECK(!lc_ack_add_range(&ack, 3, 2));
    CHECK(lc_ack_covers(&ack, 10) && !lc_ack_covers(&ack, 8));

    enum { SLOTS = 10, SIZE = 32 };
    static lc_slot_t slots[SLOTS];
    static uint8_t data[SLOTS * SIZE];
    uint8_t chunk[SIZE] = {0};
    lc_ring_t ring;
    lc_ring_init(&ring, slots, data, SLOTS, SIZE);
    uint8_t sa[16], sb[16];
    memset(sa, 0xAA, 16);
    memset(sb, 0xBB, 16);
    for (uint32_t s = 0; s < 4; s++) CHECK(lc_ring_push(&ring, sa, s, s * 8000, 0, s * 500, chunk, SIZE));
    /* Live first: newest unsent (seq 3) before backlog. */
    int idx = lc_ring_next_to_send(&ring, sa);
    CHECK(idx >= 0 && ring.slots[idx].seq == 3);
    lc_ring_mark_sent(&ring, idx);
    idx = lc_ring_next_to_send(&ring, sa);
    CHECK(idx >= 0 && ring.slots[idx].seq == 0); /* then oldest backlog */
    lc_ring_mark_sent(&ring, idx);
    /* A new live chunk preempts the backlog again. */
    CHECK(lc_ring_push(&ring, sa, 4, 4 * 8000, 0, 2000, chunk, SIZE));
    idx = lc_ring_next_to_send(&ring, sa);
    CHECK(idx >= 0 && ring.slots[idx].seq == 4);
    CHECK(lc_ring_next_to_send(&ring, sb) == -1); /* other session has nothing */

    lc_ack_t a;
    lc_ack_reset(&a);
    a.cumulative = 0;
    lc_ack_add_range(&a, 3, 3);
    CHECK(lc_ring_apply_ack(&ring, sb, &a) == 0); /* acks never cross sessions */
    CHECK(lc_ring_apply_ack(&ring, sa, &a) == 2);
    CHECK(ring.used == 3);
    CHECK(lc_ring_count_session(&ring, sa) == 3);

    lc_ring_mark_sent(&ring, lc_ring_next_to_send(&ring, sa));
    lc_ring_requeue_sent(&ring);
    CHECK(lc_ring_oldest_unsent(&ring, sa) >= 0 && ring.slots[lc_ring_oldest_unsent(&ring, sa)].seq == 1);

    /* Spill: offline and old enough → oldest; online and low usage → none. */
    CHECK(lc_ring_pick_spill(&ring, sa, 5000, false, 2000, 80) == -1);
    int sp = lc_ring_pick_spill(&ring, sa, 5000, true, 2000, 80);
    CHECK(sp >= 0 && ring.slots[sp].seq == 1);
    CHECK(lc_ring_pick_spill(&ring, sa, 1100, true, 2000, 80) == -1); /* seq1 captured at 500, age 600 */
    CHECK(lc_ring_pick_spill(&ring, sa, 1100, false, 2000, 30) >= 0); /* pressure trigger (30% used) */
    /* Slots of a session that is no longer current go to flash first, regardless of age. */
    sp = lc_ring_pick_spill(&ring, sb, 1100, false, 2000, 80);
    CHECK(sp >= 0 && ring.slots[sp].seq == 1);

    for (uint32_t s = 5; s < 12; s++) lc_ring_push(&ring, sb, s, 0, 0, 0, chunk, SIZE);
    CHECK(lc_ring_usage_pct(&ring) == 100);
    CHECK(!lc_ring_push(&ring, sb, 99, 0, 0, 0, chunk, SIZE));
}

/* ── flash log over RAM ────────────────────────────────────────────────── */
enum { SECTORS = 6 };
static uint8_t fake_flash[SECTORS * LC_FLASHLOG_SECTOR];
static int fail_header_write = 0;

static int ram_read(void *ctx, size_t off, void *dst, size_t len) {
    (void)ctx;
    memcpy(dst, fake_flash + off, len);
    return 0;
}
static int ram_write(void *ctx, size_t off, const void *src, size_t len) {
    (void)ctx;
    if (fail_header_write && off % LC_FLASHLOG_SECTOR == 0) return 0; /* power cut before header */
    const uint8_t *s = src;
    for (size_t i = 0; i < len; i++) fake_flash[off + i] &= s[i]; /* NOR: can only clear bits */
    return 0;
}
static int ram_erase(void *ctx, size_t off) {
    (void)ctx;
    memset(fake_flash + off, 0xFF, LC_FLASHLOG_SECTOR);
    return 0;
}

static void test_flashlog(void) {
    memset(fake_flash, 0xFF, sizeof fake_flash);
    const lc_flash_ops_t ops = {NULL, ram_read, ram_write, ram_erase};
    static lc_flash_slot_t index[SECTORS];
    lc_flashlog_t log;
    CHECK(lc_flashlog_mount(&log, &ops, index, SECTORS) == 0);
    CHECK(log.pending == 0);

    lc_flash_record_t rec;
    memset(&rec, 0, sizeof rec);
    memset(rec.session_id, 0xAB, 16);
    rec.codec = LC_CODEC_ADPCM;
    rec.payload_len = 100;
    uint8_t payload[LC_FLASHLOG_MAX_PAYLOAD];
    for (int i = 0; i < 100; i++) payload[i] = (uint8_t)i;
    for (uint32_t s = 0; s < 4; s++) {
        rec.seq = s;
        rec.sample_offset = s * 8000ull;
        CHECK(lc_flashlog_append(&log, &rec, payload) == 0);
    }
    CHECK(lc_flashlog_pending_for(&log, rec.session_id) == 4);

    lc_ack_t ack;
    lc_ack_reset(&ack);
    ack.cumulative = 1;
    CHECK(lc_flashlog_apply_ack(&log, rec.session_id, &ack) == 2);

    /* Reboot: index rebuilt from flash, ack state persisted. */
    static lc_flash_slot_t index2[SECTORS];
    lc_flashlog_t log2;
    CHECK(lc_flashlog_mount(&log2, &ops, index2, SECTORS) == 0);
    CHECK(log2.pending == 2);
    int oldest = lc_flashlog_oldest_unsent(&log2, rec.session_id);
    CHECK(oldest >= 0 && index2[oldest].seq == 2);
    lc_flash_record_t back;
    uint8_t back_payload[LC_FLASHLOG_MAX_PAYLOAD];
    CHECK(lc_flashlog_read(&log2, oldest, &back, back_payload) == 0);
    CHECK(back.seq == 2 && back.sample_offset == 16000 && memcmp(back_payload, payload, 100) == 0);
    lc_flashlog_mark_sent(&log2, oldest);
    CHECK(index2[lc_flashlog_oldest_unsent(&log2, rec.session_id)].seq == 3);

    /* Power cut: header never written → record ignored after reboot. */
    fail_header_write = 1;
    rec.seq = 4;
    lc_flashlog_append(&log2, &rec, payload);
    fail_header_write = 0;
    static lc_flash_slot_t index3[SECTORS];
    lc_flashlog_t log3;
    lc_flashlog_mount(&log3, &ops, index3, SECTORS);
    CHECK(log3.pending == 2);

    /* Fill: acked sectors are reused, pending ones never overwritten. */
    for (uint32_t s = 10; s < 20; s++) {
        rec.seq = s;
        int r = lc_flashlog_append(&log3, &rec, payload);
        if (log3.pending == SECTORS) {
            CHECK(r == -1 || log3.pending == SECTORS);
        }
    }
    CHECK(log3.pending == SECTORS);
    rec.seq = 99;
    CHECK(lc_flashlog_append(&log3, &rec, payload) == -1);
    CHECK(lc_flashlog_usage_pct(&log3) == 100);
    CHECK(lc_crc32((const uint8_t *)"123456789", 9) == 0xCBF43926u);
}

static void test_backoff(void) {
    CHECK(lc_backoff_delay_ms(0, 0) == 0);
    CHECK(lc_backoff_delay_ms(0, 0xFFFFFFFFu) < LC_BACKOFF_BASE_MS);
    CHECK(lc_backoff_delay_ms(3, 0x80000000u) == 2000);
    CHECK(lc_backoff_delay_ms(40, 0xFFFFFFFFu) < LC_BACKOFF_CAP_MS);
}

int main(void) {
    test_frame();
    test_adpcm();
    test_ack_and_ring();
    test_flashlog();
    test_backoff();
    printf("%d checks, %d failures\n", checks, failures);
    return failures == 0 ? EXIT_SUCCESS : EXIT_FAILURE;
}
